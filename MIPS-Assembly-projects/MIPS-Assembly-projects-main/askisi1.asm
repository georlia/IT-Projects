# Πρόγραμμα Εμφάνισης Στοιχείων Φοιτητή και Υπολογισμού Αθροίσματος σε MIPS
# Το πρόγραμμα εμφανίζει αρχικά τα προσωπικά στοιχεία του φοιτητή, όπως το ονοματεπώνυμο, τον αριθμό μητρώου και το τρέχον εξάμηνο σπουδών. 
# Στη συνέχεια, επιτρέπει στον χρήστη να εισάγει δύο ακέραιους αριθμούς και υπολογίζει το άθροισμά τους χρησιμοποιώντας τον καταχωρητή $s2. 
# Τέλος, εκτυπώνει το αποτέλεσμα με το μήνυμα «Sum=» και τερματίζει την εκτέλεση με την κατάλληλη κλήση συστήματος.
   
.data
name:      .asciiz "Georlia\n"
am:        .asciiz "2828\n"
eksamino:  .asciiz "3\n"
sum_msg:   .asciiz "Sum="

.text
main:
    # Εκτύπωση των αρχικών στοιχείων του φοιτητή
    li $v0, 4
    la $a0, name
    syscall

    li $v0, 4
    la $a0, am
    syscall

    li $v0, 4
    la $a0, eksamino
    syscall

    # Εισαγωγή δύο αριθμών από το χρήστη 
    li $v0, 5
    syscall
    move $s0, $v0

    li $v0, 5
    syscall
    move $s1, $v0

    # Υπολογισμός και εκτύπωση του αποτελέσματος 
    add $s2, $s0, $s1

    li $v0, 4
    la $a0, sum_msg
    syscall

    li $v0, 1
    move $a0, $s2
    syscall

    # Έξοδος προγράμματος 
    li $v0, 10
    syscall
